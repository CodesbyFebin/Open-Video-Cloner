'use strict';
const {spawn}=require('node:child_process');
const crypto=require('node:crypto'),path=require('node:path');
const {ffprobe,buildArgs}=require('./media');
const SAFE_ID=/^[0-9a-f-]{36}$/i;
function dockerBase(input,outputDir,name){
 const image=process.env.OVC_WORKER_IMAGE||'ovc-ffmpeg:local';
 const uid=typeof process.getuid==='function'&&process.getuid()!==0?process.getuid():65534;
 const gid=typeof process.getgid==='function'&&process.getgid()!==0?process.getgid():65534;
 return ['run','--rm','--name',name,'--network','none','--read-only','--cap-drop','ALL','--security-opt','no-new-privileges','--pids-limit','64','--memory','512m','--cpus','1','--tmpfs','/tmp:rw,noexec,nosuid,size=64m','--user',uid+':'+gid,'--mount','type=bind,src='+path.resolve(input)+',dst=/input/video,readonly','--mount','type=bind,src='+path.resolve(outputDir)+',dst=/output',image];
}
function invoke(cmd,args,{signal,progress,total,timeoutMs=3600000}={}){
 return new Promise((resolve,reject)=>{
  const child=spawn(cmd,args,{stdio:['ignore','pipe','pipe']});
  let out='',err='',buffer='',done=false,timedOut=false;
  const stop=()=>child.kill('SIGKILL');
  const timeout=setTimeout(()=>{timedOut=true;stop()},timeoutMs);
  const onAbort=()=>stop();
  signal?.addEventListener('abort',onAbort,{once:true});
  child.stdout.on('data',d=>{
   const value=d.toString();
   if(progress){buffer+=value;if(buffer.length>65536)buffer=buffer.slice(-65536);const lines=buffer.split('\n');buffer=lines.pop();for(const line of lines){const m=/^out_time_(?:ms|us)=(\d+)$/.exec(line.trim());if(m&&total>0)progress(Math.min(99,Number(m[1])/1e6/total*100))}}
   else {out+=value;if(out.length>1024*1024)stop()}
  });
  child.stderr.on('data',d=>err=(err+d.toString()).slice(-2000));
  const finish=e=>{if(done)return;done=true;clearTimeout(timeout);signal?.removeEventListener('abort',onAbort);e?reject(e):resolve(out)};
  child.on('error',finish);
  child.on('close',code=>finish(signal?.aborted?Error('Cancelled'):timedOut?Error('Worker timeout'):code!==0?Error(cmd+' exited '+code+': '+err):null));
 });
}
async function runDocker(input,output,options,progress,signal,rawArgs){
 const id=crypto.randomUUID(),name='ovc-'+id,base=dockerBase(input,path.dirname(output),name);
 const args=rawArgs?rawArgs:'/placeholder';
 const mapped=rawArgs?rawArgs.map(a=>a===input?'/input/video':a===output?'/output/'+path.basename(output):a):buildArgs('/input/video','/output/'+path.basename(output),options);
 // Do not forward arbitrary client commands: rawArgs is only generated by the timeline builder.
 try{await invoke('docker',[...base,'ffmpeg',...mapped],{signal,progress,total:options.duration})}
 finally{
  // Cancelling a docker CLI is not equivalent to stopping its container.
  // Force-remove the named container even if the CLI was killed.
  try{await invoke('docker',['rm','-f',name],{timeoutMs:15000})}catch{}
 }
}
async function probeDocker(input){
 const name='ovc-'+crypto.randomUUID();
 const base=dockerBase(input,path.dirname(input),name);
 let value;
 try{value=await invoke('docker',[...base,'ffprobe','-v','error','-show_format','-show_streams','-of','json','/input/video'],{timeoutMs:15000})}
 finally{try{await invoke('docker',['rm','-f',name],{timeoutMs:15000})}catch{}}
 const parsed=JSON.parse(value),duration=Number(parsed.format?.duration);
 if(!Number.isFinite(duration)||duration<=0||duration>86400||!parsed.streams?.some(s=>s.codec_type==='video'))throw Error('Unsupported video');
 return {duration,streams:parsed.streams.map(s=>({codec_type:s.codec_type,codec_name:s.codec_name,width:s.width,height:s.height}))};
}
module.exports={runDocker,probeDocker,dockerBase,invoke};
